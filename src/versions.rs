use serde::{Deserialize, Serialize};

#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct MinecraftVersion {
    pub id: String,
    pub name: String,
    pub category: VersionCategory,
    pub type_name: String,
    pub date: String,
    pub installed: bool,
    pub popular: bool,
    pub tag: Option<String>,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub enum VersionCategory {
    Release,
    Snapshot,
    Fabric,
    Forge,
    NeoForge,
    OptiFine,
    Old,
}

impl VersionCategory {
    pub fn label(&self) -> &'static str {
        match self {
            VersionCategory::Release => "🟩 Релизы",
            VersionCategory::Snapshot => "🔬 Снапшоты",
            VersionCategory::Fabric => "⚡ Fabric",
            VersionCategory::Forge => "🔨 Forge",
            VersionCategory::NeoForge => "🌀 NeoForge",
            VersionCategory::OptiFine => "💎 OptiFine",
            VersionCategory::Old => "📜 Старые",
        }
    }

    pub fn icon(&self) -> &'static str {
        match self {
            VersionCategory::Release => "🟩",
            VersionCategory::Snapshot => "🔬",
            VersionCategory::Fabric => "⚡",
            VersionCategory::Forge => "🔨",
            VersionCategory::NeoForge => "🌀",
            VersionCategory::OptiFine => "💎",
            VersionCategory::Old => "📜",
        }
    }
}

